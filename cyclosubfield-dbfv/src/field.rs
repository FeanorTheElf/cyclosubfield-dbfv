//! Hardcoded descriptions of the abelian number fields used to instantiate (d)BFV.
//!
//! A field `L` is the compositum of two linearly disjoint fields `K` and `Lʼ`:
//!  - `K` is a subfield of a cyclotomic field `M_K = Q(ζ_(m_K))`, `m_K` odd and squarefree, such
//!    that `(2)` splits completely in `K`.
//!  - `Lʼ` is a subfield of a prime cyclotomic field `Mʼ = Q(ζ_mʼ)`, whose residue degree `f_Lʼ` at
//!    `(2)` is divisible by the degree `d = lcm_(p | m_K) d_p` that the homomorphic CRT transform
//!    needs (see [`FieldDescriptor::crt_transform_degree()`]).
//!
//! Note that `(2)` need *not* be totally inert in `Lʼ` — `f_Lʼ` may be a proper divisor of
//! `[Lʼ : Q]`, in which case `O_Lʼ/(2^e)` is a product of several Galois rings rather than a
//! single one; see [`FieldDescriptor::lprime_embedding_transversal()`].
//!
//! We write `M = Mʼ M_K = Q(ζ_m)` with `m = mʼ m_K`, and identify `Gal(M|Q) = (Z/mZ)*`.
//! All fields are then described by subgroups of `(Z/mZ)*`, represented as plain integers.
//!
//! In contrast to the reference implementation, the data defining a field (the subgroup
//! `Gal(M|L)` and cyclic decompositions of `Gal(Lʼ|Q)` and `Gal(K|Q)`) is hardcoded, since
//! computing it requires a lot of group-theoretic machinery. Note that hardcoding the cyclic
//! decompositions (rather than recomputing them) is necessary anyway to fix the concrete
//! isomorphism `Gal(L|Q) -> C_n1 x ... x C_nr`, which determines the ordering of the period
//! basis.
//!
//! # The period basis
//!
//! The period basis of `L` is the normal basis given by the Gaussian periods
//! `η_σ = Tr_(M|L)(σ(ζ_m))`, where `σ` runs through a transversal of `Gal(M|L)` in `Gal(M|Q)`.
//! The transversal is ordered by [`FieldDescriptor::lq_transversal()`], whose order is derived
//! from the fixed cyclic decomposition; concretely, the element at (flat, row-major) index
//! `(e_1, ..., e_r)` is `g_1^e_1 ... g_r^e_r`, with the `Lʼ`-factors coming first.

use std::collections::{HashMap, HashSet};

use crate::bfv::SK_HWT;

fn mul_mod(a: u64, b: u64, m: u64) -> u64 { ((a as u128 * b as u128) % m as u128) as u64 }

fn pow_mod(mut b: u64, mut e: u64, m: u64) -> u64 {
    let mut result = 1 % m;
    b %= m;
    while e > 0 {
        if e & 1 == 1 {
            result = mul_mod(result, b, m);
        }
        b = mul_mod(b, b, m);
        e >>= 1;
    }
    return result;
}

/// Computes the subgroup of `(Z/mZ)*` generated by `gens`, as a list of elements.
fn subgroup_elements(gens: &[u64], m: u64) -> Vec<u64> {
    let mut elements = HashSet::new();
    elements.insert(1);
    let mut frontier = vec![1];
    while let Some(x) = frontier.pop() {
        for g in gens {
            let y = mul_mod(x, *g, m);
            if elements.insert(y) {
                frontier.push(y);
            }
        }
    }
    let mut result = elements.into_iter().collect::<Vec<_>>();
    result.sort_unstable();
    return result;
}

fn gcd(a: u64, b: u64) -> u64 { if b == 0 { a } else { gcd(b, a % b) } }

fn lcm(a: u64, b: u64) -> u64 { a / gcd(a, b) * b }

/// The hardcoded data defining a field; see the module-level documentation.
pub struct FieldDescriptorData {
    pub m: u64,
    /// `1` if `Lʼ = Q`
    pub m_prime: u64,
    pub gal_mprime_lprime_gens: Vec<u64>,
    pub gal_mk_k_gens: Vec<u64>,
    /// pairs `(g_i, n_i)` such that `C_n1 x ... x C_nr -> Gal(Lʼ|Q), e_i -> g_i mod Gal(M|Lʼ)`
    /// is an isomorphism
    pub gal_lprime_q_cyclic: Vec<(u64, usize)>,
    /// pairs `(g_i, n_i)` such that `C_n1 x ... x C_nr -> Gal(K|Q), e_i -> g_i mod Gal(M|K)`
    /// is an isomorphism
    pub gal_kq_cyclic: Vec<(u64, usize)>,
    /// a (low) estimate for the pbinf operator norm of a random ring element with pbinf norm <= 1
    log2_pb_normalized_pb_op_norm_estimate: f64,
    /// a (low) estimate for the pbinf operator norm of the secret key, assuming sk_hwt = 128
    log2_sk_pb_op_norm_estimate: f64,
}

/// Per-prime data, for a prime `p | m`.
pub struct PrimeInfo {
    p: u64,
    /// generator of the inertia group `I_p`, i.e. the `(Z/pZ)*`-factor of `(Z/mZ)*`
    i_p_gen: u64,
    /// order of `2` in `(Z/pZ)*`
    f_p: usize,
    /// the elements of `H_p = I_p ∩ Gal(M|L)`
    h_p: Vec<u64>,
    /// order of the projection of `2` into `I_p / H_p`
    d_p: usize,
}

impl PrimeInfo {
    pub fn p(&self) -> u64 { self.p }

    /// A generator of the inertia group `I_p <= Gal(M|Q)`. Since `I_p` is cyclic, its image
    /// also generates the quotient `J_p = I_p / H_p`, the group that the homomorphic CRT
    /// transform's factor for `p` is cyclic over.
    pub fn i_p_gen(&self) -> u64 { self.i_p_gen }

    /// The order of the Frobenius (i.e. of `2`) in `I_p`.
    pub fn f_p(&self) -> usize { self.f_p }

    /// The elements of `H_p = I_p ∩ Gal(M|L)`.
    pub fn h_p(&self) -> &[u64] { &self.h_p }

    /// The order of the Frobenius (i.e. of `2`) in `I_p / H_p`.
    pub fn d_p(&self) -> usize { self.d_p }

    /// The order of `J_p = I_p / H_p`.
    pub fn j_p_order(&self) -> usize { (self.p as usize - 1) / self.h_p.len() }
}

/// Describes a number field `L` that can be used to instantiate (d)BFV; see the module-level
/// documentation. Constructed from hardcoded [`FieldDescriptorData`].
pub struct FieldDescriptor {
    m: u64,
    m_prime: u64,
    /// all prime factors of `m`, with `mʼ` first (if `mʼ != 1`)
    m_factors: Vec<u64>,
    /// cyclic decomposition of `Gal(L|Q)`; the `Lʼ`-factors first, then the `K`-factors
    lq_cyclic: Vec<(u64, usize)>,
    /// number of `Lʼ`-factors at the start of `lq_cyclic`
    lprime_factor_count: usize,
    deg_l: usize,
    deg_k: usize,
    deg_lprime: usize,
    /// the elements of `H = Gal(M|L)`
    gal_ml: Vec<u64>,
    /// the elements of `Gal(Mʼ|Lʼ)`, embedded into `(Z/mZ)*`
    gal_mprime_lprime: Vec<u64>,
    /// the elements of `Gal(M_K|K)`, embedded into `(Z/mZ)*`
    gal_mk_k: Vec<u64>,
    /// maps each element of [`FieldDescriptor::lq_transversal()`] to its flat index
    transversal_index: HashMap<u64, usize>,
    /// aligned with `m_factors`
    prime_info: Vec<PrimeInfo>,
    /// a (low) estimate for the pbinf operator norm of a random ring element with pbinf norm <= 1
    log2_pb_normalized_pb_op_norm_estimate: f64,
    /// a (low) estimate for the pbinf operator norm of the secret key, assuming sk_hwt = 128
    log2_sk_pb_op_norm_estimate: f64,
}

impl FieldDescriptor {
    pub fn new(data: FieldDescriptorData) -> Self {
        let m = data.m;
        assert!(m % 2 == 1);
        assert!(data.m_prime == 1 || m % data.m_prime == 0);

        let mut m_factors = Vec::new();
        if data.m_prime != 1 {
            m_factors.push(data.m_prime);
        }
        let mut rest = m / data.m_prime;
        let mut p = 3;
        while rest > 1 {
            if rest % p == 0 {
                rest /= p;
                assert!(rest % p != 0, "m must be squarefree");
                m_factors.push(p);
            }
            p += 2;
        }
        let phi_m: u64 = m_factors.iter().map(|p| p - 1).product();

        let gal_mprime_lprime = subgroup_elements(&data.gal_mprime_lprime_gens, m);
        let gal_mk_k = subgroup_elements(&data.gal_mk_k_gens, m);
        let all_gens = data.gal_mprime_lprime_gens.iter().chain(&data.gal_mk_k_gens).copied().collect::<Vec<_>>();
        let gal_ml = subgroup_elements(&all_gens, m);

        let lq_cyclic = data.gal_lprime_q_cyclic.iter().chain(&data.gal_kq_cyclic).copied().collect::<Vec<_>>();
        let deg_l = lq_cyclic.iter().map(|(_, n)| n).product::<usize>();
        let deg_lprime = data.gal_lprime_q_cyclic.iter().map(|(_, n)| n).product::<usize>();
        let deg_k = deg_l / deg_lprime;
        assert_eq!(phi_m as usize, deg_l * gal_ml.len(), "transversal size must match [L : Q]");

        let mut result = Self {
            m,
            m_prime: data.m_prime,
            m_factors,
            lprime_factor_count: data.gal_lprime_q_cyclic.len(),
            lq_cyclic,
            deg_l,
            deg_k,
            deg_lprime,
            gal_ml,
            gal_mprime_lprime,
            gal_mk_k,
            transversal_index: HashMap::new(),
            prime_info: Vec::new(),
            log2_pb_normalized_pb_op_norm_estimate: data.log2_pb_normalized_pb_op_norm_estimate,
            log2_sk_pb_op_norm_estimate: data.log2_sk_pb_op_norm_estimate,
        };

        let mut transversal_index = HashMap::with_capacity(deg_l);
        for (i, g) in result.lq_transversal().into_iter().enumerate() {
            let old = transversal_index.insert(g, i);
            assert!(old.is_none(), "generators do not induce an isomorphism C_n1 x ... x C_nr -> Gal(L|Q)");
        }
        result.transversal_index = transversal_index;
        result.init_per_prime_info();
        return result;
    }

    fn init_per_prime_info(&mut self) {
        let m = self.m;
        let gal_ml_set = self.gal_ml.iter().copied().collect::<HashSet<_>>();
        for &p in &self.m_factors {
            // find a generator of (Z/pZ)* and embed it into (Z/mZ)* as ≡ 1 mod m/p
            let mut p_minus_1_factors = Vec::new();
            let mut rest = p - 1;
            let mut f = 2;
            while rest > 1 {
                if rest % f == 0 {
                    p_minus_1_factors.push(f);
                    while rest % f == 0 {
                        rest /= f;
                    }
                }
                f += 1;
            }
            let generator =
                (2..p).find(|g| p_minus_1_factors.iter().all(|r| pow_mod(*g, (p - 1) / r, p) != 1)).unwrap();
            let i_p_gen = crt2(generator, p, 1, m / p);

            let f_p = element_order(2 % p, p) as usize;
            let h_p =
                (0..(p - 1)).map(|e| pow_mod(i_p_gen, e, m)).filter(|x| gal_ml_set.contains(x)).collect::<Vec<_>>();
            let d_p = f_p / gcd(f_p as u64, h_p.len() as u64) as usize;
            self.prime_info.push(PrimeInfo { p, i_p_gen, f_p, h_p, d_p });
        }
        // The transform coefficients live in the degree-`d` unramified extension of `Z/2^eZ`, and
        // have to be representable in `O_Lʼ/(2^e)`, i.e. in each of its residue rings
        // `GR(2^e, f_Lʼ)`. This requires `d | f_Lʼ` — *not* `d = [Lʼ : Q]`, which would
        // additionally force `(2)` to be totally inert in `Lʼ`.
        let d = self.crt_transform_degree();
        assert!(
            self.lprime_residue_degree() % d == 0,
            "the residue degree of (2) in Lʼ must be divisible by the degree required by the CRT transform"
        );
    }

    pub fn m(&self) -> u64 { self.m }

    pub fn m_prime(&self) -> u64 { self.m_prime }

    pub fn m_k(&self) -> u64 { self.m / self.m_prime }

    pub fn deg_l(&self) -> usize { self.deg_l }

    pub fn deg_k(&self) -> usize { self.deg_k }

    pub fn deg_lprime(&self) -> usize { self.deg_lprime }

    pub fn deg_mprime(&self) -> usize { if self.m_prime == 1 { 1 } else { self.m_prime as usize - 1 } }

    pub fn m_factors(&self) -> &[u64] { &self.m_factors }

    pub fn m_k_factors(&self) -> &[u64] { if self.m_prime == 1 { &self.m_factors } else { &self.m_factors[1..] } }

    /// Returns `(g_1, n_1), ..., (g_r, n_r)` such that we have an isomorphism
    /// ```text
    ///   C_n1 x ... x C_nr  ->  Gal(L|Q),    e_i  ->  g_i mod Gal(M|L)
    /// ```
    /// The `Lʼ`-factors come first, followed by the `K`-factors. This isomorphism induces the
    /// ordering of the period basis, via [`FieldDescriptor::lq_transversal()`].
    pub fn lq_cyclic_decomposition(&self) -> &[(u64, usize)] { &self.lq_cyclic }

    /// The `Lʼ`-part of [`FieldDescriptor::lq_cyclic_decomposition()`].
    pub fn lprime_q_cyclic_decomposition(&self) -> &[(u64, usize)] { &self.lq_cyclic[..self.lprime_factor_count] }

    /// The `K`-part of [`FieldDescriptor::lq_cyclic_decomposition()`].
    pub fn kq_cyclic_decomposition(&self) -> &[(u64, usize)] { &self.lq_cyclic[self.lprime_factor_count..] }

    /// The lengths `n_1, ..., n_r` of [`FieldDescriptor::lq_cyclic_decomposition()`].
    pub fn lq_cyclic_orders(&self) -> Vec<usize> { self.lq_cyclic.iter().map(|(_, n)| *n).collect() }

    /// The elements of `Gal(M|L)`.
    pub fn gal_ml_elements(&self) -> &[u64] { &self.gal_ml }

    /// The elements of `Gal(Mʼ|Lʼ)`, embedded into `Gal(M|Q)`.
    pub fn gal_mprime_lprime_elements(&self) -> &[u64] { &self.gal_mprime_lprime }

    /// The elements of `Gal(M_K|K)`, embedded into `Gal(M|Q)`.
    pub fn gal_mk_k_elements(&self) -> &[u64] { &self.gal_mk_k }

    fn transversal_of(&self, factors: &[(u64, usize)]) -> Vec<u64> {
        let mut result = vec![1u64];
        for (g, n) in factors {
            let mut new_result = Vec::with_capacity(result.len() * n);
            let mut power = 1;
            let mut powers = Vec::with_capacity(*n);
            for _ in 0..*n {
                powers.push(power);
                power = mul_mod(power, *g, self.m);
            }
            for x in &result {
                for p in &powers {
                    new_result.push(mul_mod(*x, *p, self.m));
                }
            }
            result = new_result;
        }
        return result;
    }

    /// Returns a representative in `Gal(M|Q)` for every element of `Gal(L|Q) = Gal(M|Q)/Gal(M|L)`,
    /// ordered such that the element with mixed-radix index `(e_1, ..., e_r)` (first factor most
    /// significant) is `g_1^e_1 ... g_r^e_r`. This ordering is exactly the ordering of the period
    /// basis of `L`.
    pub fn lq_transversal(&self) -> Vec<u64> { self.transversal_of(&self.lq_cyclic) }

    /// Like [`FieldDescriptor::lq_transversal()`], but for `Gal(K|Q)`; induces the ordering of
    /// the period basis of `K`.
    pub fn kq_transversal(&self) -> Vec<u64> { self.transversal_of(self.kq_cyclic_decomposition()) }

    /// Like [`FieldDescriptor::lq_transversal()`], but for `Gal(Lʼ|Q)`; induces the ordering of
    /// the period basis of `Lʼ`.
    pub fn lprime_q_transversal(&self) -> Vec<u64> { self.transversal_of(self.lprime_q_cyclic_decomposition()) }

    /// Returns the exponents `(e_1, ..., e_r)` such that `g = g_1^e_1 ... g_r^e_r mod Gal(M|L)`,
    /// w.r.t. the cyclic decomposition [`FieldDescriptor::lq_cyclic_decomposition()`].
    ///
    /// The Galois automorphism `g` acts on period-basis coefficients by cyclically shifting the
    /// `i`-th dimension by `e_i`.
    pub fn gal_to_shift(&self, g: u64) -> Vec<i64> {
        let mut index = self.coset_index(g).expect("not an element of (Z/mZ)* or inconsistent subgroup data");
        let mut result = vec![0; self.lq_cyclic.len()];
        for (i, (_, n)) in self.lq_cyclic.iter().enumerate().rev() {
            result[i] = (index % n) as i64;
            index /= n;
        }
        return result;
    }

    /// Returns the index in [`FieldDescriptor::lq_transversal()`] of the coset `g Gal(M|L)`.
    pub fn coset_index(&self, g: u64) -> Option<usize> {
        assert!(gcd(g % self.m, self.m) == 1);
        self.gal_ml.iter().find_map(|h| self.transversal_index.get(&mul_mod(g % self.m, *h, self.m))).copied()
    }

    /// The per-prime information for the prime `p | m`.
    pub fn prime_info(&self, p: u64) -> &PrimeInfo {
        self.prime_info.iter().find(|info| info.p == p).expect("prime doesn't divide m")
    }

    /// The degree `d = lcm_(p | m_K) d_p` of the smallest unramified extension of `Z/2^eZ` that
    /// contains all coefficients of the homomorphic CRT transform (see
    /// [`crate::bootstrap::homcrt`]). It must divide
    /// [`FieldDescriptor::lprime_residue_degree()`], so that those coefficients can
    /// be represented by elements of `O_Lʼ/(2^e)`.
    pub fn crt_transform_degree(&self) -> usize {
        self.prime_info.iter().filter(|info| info.p != self.m_prime).fold(1u64, |x, info| lcm(x, info.d_p as u64))
            as usize
    }

    /// The residue degree `f_Lʼ` of `(2)` in `Lʼ`, i.e. the order of the Frobenius in
    /// `Gal(Lʼ|Q)`. Consequently `O_Lʼ/(2^e)` is a product of `[Lʼ : Q] / f_Lʼ` copies of the
    /// Galois ring `GR(2^e, f_Lʼ)`, one per prime of `Lʼ` above `2`.
    pub fn lprime_residue_degree(&self) -> usize {
        if self.m_prime == 1 { 1 } else { self.prime_info(self.m_prime).d_p }
    }

    /// The order of the Frobenius (i.e. of `2`) in `Gal(Mʼ|Q) = (Z/mʼZ)*`; the smallest degree
    /// of an unramified extension of `Z/2^eZ` that contains a primitive `mʼ`-th root of unity.
    pub fn mprime_frobenius_order(&self) -> usize {
        if self.m_prime == 1 { 1 } else { self.prime_info(self.m_prime).f_p }
    }

    /// Returns one element of [`FieldDescriptor::lprime_q_transversal()`] per prime of `Lʼ`
    /// above `2`, i.e. a transversal of the decomposition group `<Frob_2>` in `Gal(Lʼ|Q)`.
    ///
    /// Reducing `O_Lʼ` modulo a prime `P` above `2` embeds `O_Lʼ/(2^e)` into a Galois ring only
    /// after choosing `P`; precomposing one such reduction with the `γ` returned here yields
    /// exactly the pairwise distinct reductions, one per prime. The homomorphic CRT transform
    /// needs all of them: its coefficients must take the prescribed value in *every* residue
    /// ring of `O_Lʼ/(2^e)`, since the plaintext ring `O_L/(2^e)` has slots above every prime of
    /// `Lʼ` (see [`crate::bootstrap::homcrt::CRTTransformFactor::new()`]). If `(2)` is totally
    /// inert in `Lʼ`, this is the single element `1`.
    pub fn lprime_embedding_transversal(&self) -> Vec<u64> {
        if self.m_prime == 1 {
            return vec![1];
        }
        // the decomposition group of (2) in Gal(Mʼ|Q), i.e. < 2, Gal(Mʼ|Lʼ) > <= (Z/mʼZ)*
        let mut gens = vec![2 % self.m_prime];
        gens.extend(self.gal_mprime_lprime.iter().map(|h| h % self.m_prime));
        let decomposition = subgroup_elements(&gens, self.m_prime);
        let mut seen = HashSet::new();
        let mut result = Vec::new();
        for g in self.lprime_q_transversal() {
            // the smallest element of the coset `g <2, Gal(Mʼ|Lʼ)>` identifies the prime
            let coset = decomposition.iter().map(|s| mul_mod(g % self.m_prime, *s, self.m_prime)).min().unwrap();
            if seen.insert(coset) {
                result.push(g);
            }
        }
        assert_eq!(self.deg_lprime / self.lprime_residue_degree(), result.len());
        return result;
    }

    /// The period-basis coefficients (in [`FieldDescriptor::lprime_q_transversal()`] order) of an
    /// `Lʼ`-element `α` with `Tr_(Lʼ|Q)(α) = 1`, used by bootstrapping to cancel the `[Lʼ : Q]`
    /// trace factor without amplifying noise (see [`crate::bootstrap`]).
    ///
    /// A general trace-form correction — `α` with `Tr_(Lʼ|Q)(α x) = x_id` for every `x`, i.e.
    /// `T α = e_id` for the trace form `T = (Tr_(Lʼ|Q)(σ(bʼ) τ(bʼ)))_(σ,τ)` — exists because `2`
    /// is unramified in `Lʼ`, so `det T = disc(Lʼ)` is odd and the system is solvable modulo the
    /// (power-of-two) plaintext modulus. That `α` handles arbitrary `x`; its coefficients are
    /// `Θ(2^e)`-sized modulo `2^e`, so applying it keeps the noise growth reasonable only if the
    /// multiplication dBFV-decomposes `α` (its digits are then small). Here we avoid both the
    /// linear solve and the decomposition: the bootstrapped message is `K`-valued (fixed by
    /// `Gal(L|K)`), so the `L|K`-trace acts on it as `Tr_(Lʼ|Q)`, and *any* `α` with
    /// `Tr_(Lʼ|Q)(α) = 1` already recovers the message. The cheapest such `α` is a single Gaussian
    /// period `α = c · η_id`, whose trace is `c · Tr_(Lʼ|Q)(η_id)`; the period basis induced by `M`
    /// gives `Tr_(Lʼ|Q)(η_id) = scale_mprime_to_m · Tr_(Lʼ|Q)(bʼ) = scale_mprime_to_m · μ(mʼ)`
    /// (a sign, since `Tr_(Lʼ|Q)(bʼ) = Tr_(Mʼ|Q)(ζ_mʼ) = μ(mʼ)`). Hence `c` is that same sign.
    pub fn lprime_trace_one_coeffs(&self) -> Vec<i128> {
        // μ(mʼ) = -1 for the (prime) mʼ, +1 for Lʼ = Q
        let mu_mprime = if self.m_prime == 1 { 1 } else { -1 };
        let mut coeffs = vec![0i128; self.deg_lprime];
        coeffs[0] = (self.scale_mprime_to_m_period_basis() * mu_mprime) as i128;
        return coeffs;
    }

    /// The order of roots of unity that each RNS factor `q` must support, i.e. every RNS prime
    /// must satisfy `q ≡ 1 mod rou_order()`. This makes `q` split completely in `M` (hence in
    /// `L`), and provides the roots of unity for the group-NTTs underlying the CRT transform.
    pub fn rou_order(&self) -> u64 { self.m * self.lq_cyclic.iter().map(|(_, n)| *n as u64).fold(1, lcm) }

    /// Returns the value `t in {-1, 1}` such that the period basis of `Q` induced by `Q` (i.e.
    /// the basis `{ 1 }`) is `t` times the period basis of `Q` induced by `M`.
    ///
    /// Concretely, the period basis of `Q` induced by `M` is `Tr_(M|Q)(ζ_m) = μ(m) = (-1)^r`
    /// with `r` the number of prime factors of `m`.
    pub fn scale_q_to_m_period_basis(&self) -> i64 { if self.m_factors.len() % 2 == 1 { -1 } else { 1 } }

    /// Returns the value `t in {-1, 1}` such that the period basis of `Lʼ` induced by `Mʼ` is
    /// `t` times the period basis of `Lʼ` induced by `M`.
    pub fn scale_mprime_to_m_period_basis(&self) -> i64 {
        self.scale_q_to_m_period_basis() * self.scale_m_k_to_m_period_basis()
    }

    /// Returns the value `t in {-1, 1}` such that the period basis of `K` induced by `M_K` is
    /// `t` times the period basis of `K` induced by `M`.
    pub fn scale_m_k_to_m_period_basis(&self) -> i64 { if self.m_prime == 1 { 1 } else { -1 } }

    /// Returns a (low) estimate for the value `log2( |e_mul|_pbinf / max(|e_l|_pbinf, |e_r|_pbinf)
    /// )`, where `e_l` and `e_r` are the noise terms in two BFV ciphertexts, and `e_mul` is the
    /// error term in the homomorphic product of the ciphertexts. Note that in the case of dBFV,
    /// this also holds, but for `t := b`. Here `|x|_pbinf` is the l_inf-norm of coefficients in
    /// the period-basis representation of `x`.
    pub fn noise_growth_hom_mul_lower_estimate(&self, t: i128) -> f64 {
        assert_eq!(128, SK_HWT, "only the case sk_hwt = 128 is currently implemented");
        (t as f64).log2() + self.log2_sk_pb_op_norm_estimate + self.log2_pb_normalized_pb_op_norm_estimate
    }

    /// Returns a (low) estimate for the value `log2( |e_scale|_pbinf / |e_in|_pbinf )`, where
    /// `e_in` is the noise terms in an input BFV ciphertext, and `e_scale` is the error term in the
    /// result of a homomorphic plaintext-ciphertext product. Note that in the case of dBFV,
    /// this also holds, but for `t := b`. Here `|x|_pbinf` is the l_inf-norm of coefficients in
    /// the period-basis representation of `x`.
    pub fn noise_growth_hom_mul_plain_lower_estimate(&self, t: i128) -> f64 {
        (t as f64).log2() + self.log2_pb_normalized_pb_op_norm_estimate
    }

    /// Returns a (low) estimate for the value `log2( |e_scale|_pbinf / |e_in|_pbinf )`, where
    /// `e_in` is the noise terms in an input BFV ciphertext, and `e_scale` is the error term in the
    /// result of a homomorphic plaintext-ciphertext product. Note that in the case of dBFV,
    /// this also holds, but for `t := b`. Here `|x|_pbinf` is the l_inf-norm of coefficients in
    /// the period-basis representation of `x`.
    pub fn noise_growth_hom_mul_scalar_lower_estimate(&self, t: i128) -> f64 { (t as f64).log2() }
}

/// Computes the multiplicative order of `x` modulo `n`.
fn element_order(x: u64, n: u64) -> u64 {
    let mut current = x % n;
    let mut order = 1;
    while current != 1 {
        current = mul_mod(current, x, n);
        order += 1;
    }
    return order;
}

/// Computes the inverse of `a` modulo `n`, for coprime `a, n`.
pub fn inv_mod(a: u64, n: u64) -> u64 {
    let (mut old_r, mut r) = (a as i128 % n as i128, n as i128);
    let (mut old_s, mut s) = (1i128, 0i128);
    while r != 0 {
        let quotient = old_r / r;
        (old_r, r) = (r, old_r - quotient * r);
        (old_s, s) = (s, old_s - quotient * s);
    }
    assert!(old_r == 1 || old_r == -1, "elements are not coprime");
    return (old_s * old_r).rem_euclid(n as i128) as u64;
}

/// Computes the element that is `≡ a1 mod m1` and `≡ a2 mod m2`, for coprime `m1, m2`.
pub fn crt2(a1: u64, m1: u64, a2: u64, m2: u64) -> u64 {
    if m1 == 1 {
        return a2 % m2;
    } else if m2 == 1 {
        return a1 % m1;
    }
    let m1_inv_mod_m2 = inv_mod(m1 % m2, m2);
    let k = mul_mod((a2 + m2 - a1 % m2) % m2, m1_inv_mod_m2, m2);
    return (a1 as u128 + m1 as u128 * k as u128) as u64 % (m1 as u64 * m2) as u64;
}

