    /// For every field, each embedding representative must sit in a distinct coset of the
    /// decomposition group, and the totally-inert fields must have exactly one embedding.
    #[test]
    fn test_lprime_embedding_transversal() {
        feanor_tracing::DelayedLogger::init_test();
        let fields = [
            field_2(),
            field_16(),
            field_18(),
            field_32(),
            field_192(),
            field_24576(),
            field_32768(),
            field_32768_ex(),
            field_36864(),
            field_49152(),
            field_49152_ex(),
            field_65536(),
        ];
        for field in fields {
            let embeddings = field.lprime_embedding_transversal();
            assert_eq!(field.deg_lprime() / field.lprime_residue_degree(), embeddings.len());
            let m_prime = field.m_prime();
            if m_prime == 1 {
                assert_eq!(vec![1], embeddings);
                continue;
            }
            // the decomposition group < 2, Gal(Mʼ|Lʼ) > of (2) in Gal(Mʼ|Q) = (Z/mʼZ)*
            let decomposition = (0..field.lprime_residue_degree())
                .flat_map(|k| {
                    field
                        .gal_mprime_lprime_elements()
                        .iter()
                        .map(move |h| mul_mod(pow_mod(2, k as u64, m_prime), *h % m_prime, m_prime))
                })
                .collect::<Vec<_>>();
            let mut distinct = decomposition.clone();
            distinct.sort_unstable();
            distinct.dedup();
            // the order of the decomposition group pins down `lprime_residue_degree()`
            assert_eq!(decomposition.len(), distinct.len());
            assert_eq!(field.deg_mprime() / embeddings.len(), distinct.len());
            for (i, g) in embeddings.iter().enumerate() {
                for h in &embeddings[..i] {
                    // two representatives agree iff `g h^-1` lies in the decomposition group
                    let quotient = mul_mod(*g % m_prime, inv_mod(*h % m_prime, m_prime), m_prime);
                    assert!(!decomposition.contains(&quotient), "embeddings {} and {} coincide", g, h);
                }
            }
        }
    }

